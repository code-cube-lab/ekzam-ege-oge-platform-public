export type FoundationChallenge = {
  prompt: string;
  options: string[];
  answerIndex: number;
  misconception: string;
  explanation: string;
};

export type FoundationChapterSeed = {
  title: string;
  goal: string;
  rule: string;
  example: string;
  counterExample: string;
  challenge: FoundationChallenge;
  retry: FoundationChallenge;
};

