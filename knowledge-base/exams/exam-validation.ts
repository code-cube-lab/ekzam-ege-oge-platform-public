export type ExamRouteValidation = {
  status: "preview-ready" | "blocked";
  label: string;
  checkedAt: string;
  sourceUrl: string;
  reason: string;
  requirements: string[];
};

type SubjectValidation = {
  ege: ExamRouteValidation;
  oge?: ExamRouteValidation;
};

const officialSources = {
  ege: "https://fipi.ru/ege/demoversii-specifikacii-kodifikatory",
  oge: "https://fipi.ru/oge/demoversii-specifikacii-kodifikatory",
} as const;

function blocked(level: "ege" | "oge", reason: string, requirements: string[]): ExamRouteValidation {
  return {
    status: "blocked",
    label: "Банк закрыт до предметной проверки",
    checkedAt: "2026-07-28",
    sourceUrl: officialSources[level],
    reason,
    requirements,
  };
}

