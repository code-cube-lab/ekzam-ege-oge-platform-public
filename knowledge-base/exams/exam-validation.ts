export function getExamRouteValidation(level: "oge" | "ege", subject: ExamSubjectSlug) {
  return examRouteValidation[subject][level] ?? blocked(
    level,
    "Для этого сочетания экзамена и предмета нет подтверждённого маршрута.",
    ["сверить доступность предмета и структуру экзамена на ФИПИ"],
  );
}
