const SUBJECT = "Биология";
const SOURCE = "Авторский материал · линия и способ ответа сверены со спецификацией ФИПИ-2026";

function common(variant, line, topic, prompt, solution, extra = {}) {
  return {
    id: `biology-v${variant}-${line}`,
    subject: SUBJECT,
    number: `Задание ${line}`,
    examYear: 2026,
    sourceLabel: SOURCE,
    difficulty: line >= 22 ? "высокий" : line >= 6 ? "повышенный" : "базовый",
    topic,
    theory: extra.theory ?? "Свяжите наблюдаемый признак с уровнем организации живого и проверьте причинно-следственную связь.",
    prompt,
    answer: extra.answer ?? "teacher-review",
    solution,
    ...extra,
  };
}

function blank(variant, line, topic, prompt, answer, solution, extra = {}) {
  return common(variant, line, topic, prompt, solution, {
    kind: extra.kind ?? "text",
    format: extra.format ?? "краткий ответ",
    interaction: "exam-blank",
    answer: String(answer),
    responseInstruction: extra.responseInstruction ?? "Запишите ответ без пробелов и дополнительных символов.",
    ...extra,
  });
}

function digits(variant, line, topic, prompt, options, answer, solution, extra = {}) {
  return blank(variant, line, topic, prompt, answer, solution, {
    kind: "text",
    format: extra.format ?? "последовательность цифр",
    options,
    answerOrder: extra.answerOrder ?? "fixed",
    responseInstruction: "Запишите последовательность цифр без пробелов.",
    ...extra,
  });
}

function extended(variant, line, topic, prompt, solution, maxScore = 3, extra = {}) {
  return common(variant, line, topic, prompt, solution, {
    kind: "extended",
    format: "развёрнутый ответ",
    answer: "teacher-review",
    responseInstruction: "Запишите последовательное объяснение с биологическими терминами и причинно-следственными связями.",
    maxScore,
    ...extra,
  });
}

