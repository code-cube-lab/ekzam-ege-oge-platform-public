const SUBJECT = "Химия";
const SOURCE = "Авторский материал · линия и способ ответа сверены со спецификацией ФИПИ-2026";

function clean(value) {
  return String(Math.round((value + Number.EPSILON) * 1000000) / 1000000);
}

function common(variant, line, topic, prompt, solution, extra = {}) {
  return {
    id: `chemistry-v${variant}-${line}`,
    subject: SUBJECT,
    number: `Задание ${line}`,
    examYear: 2026,
    sourceLabel: SOURCE,
    difficulty: line >= 29 ? "высокий" : line >= 6 ? "повышенный" : "базовый",
    topic,
    theory: extra.theory ?? "Определите класс вещества и тип процесса, затем проверьте сохранение атомов и заряда.",
    prompt,
    answer: extra.answer ?? "teacher-review",
    solution,
    ...extra,
  };
}

function blank(variant, line, topic, prompt, answer, solution, extra = {}) {
  return common(variant, line, topic, prompt, solution, {
    kind: extra.kind ?? "text",
    format: extra.format ?? "краткий ответ",
    interaction: "exam-blank",
    answer: String(answer),
    responseInstruction: extra.responseInstruction ?? "Запишите ответ без пробелов и лишних символов.",
    ...extra,
  });
}

function digits(variant, line, topic, prompt, options, answer, solution, extra = {}) {
  return blank(variant, line, topic, prompt, answer, solution, {
    kind: "text",
    format: extra.format ?? "последовательность цифр",
    options,
    answerOrder: extra.answerOrder ?? "fixed",
    responseInstruction: extra.responseInstruction ?? "Запишите последовательность цифр без пробелов.",
    ...extra,
  });
}

function extended(variant, line, topic, prompt, solution, maxScore) {
  return common(variant, line, topic, prompt, solution, {
    kind: "extended",
    format: "развёрнутое решение",
    answer: "teacher-review",
    responseInstruction: "Запишите уравнения реакций, электронный или ионный баланс и расчёты, необходимые по условию.",
    maxScore,
  });
}

