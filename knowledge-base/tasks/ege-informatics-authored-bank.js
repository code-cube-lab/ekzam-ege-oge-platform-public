const SUBJECT = "Информатика";
const SOURCE = "Авторский материал · линия и способ ответа сверены со спецификацией ФИПИ-2026";

function task(variant, line, topic, prompt, answer, solution, extra = {}) {
  return {
    id: `informatics-v${variant}-${line}`,
    subject: SUBJECT,
    number: `Задание ${line}`,
    examYear: 2026,
    sourceLabel: SOURCE,
    difficulty: line >= 24 ? "высокий" : line >= 17 ? "повышенный" : "базовый",
    topic,
    theory: extra.theory ?? "Постройте точную модель условия, проверьте граничные случаи и только затем запишите краткий ответ.",
    prompt: `${prompt}\n\nНомер тренировочного варианта: ${variant}.`,
    kind: extra.kind ?? "number",
    format: extra.format ?? "краткий ответ",
    interaction: "exam-blank",
    answer: String(answer),
    responseInstruction: extra.responseInstruction ?? "Запишите только ответ без единиц измерения и пояснений.",
    solution,
    maxScore: extra.maxScore ?? (line >= 26 ? 2 : 1),
    stimulus: extra.stimulus,
    code: extra.code,
    attachment: extra.attachment,
    resourceStatus: extra.resourceStatus,
  };
}

