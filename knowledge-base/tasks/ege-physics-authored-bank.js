const SUBJECT = "Физика";
const SOURCE = "Авторский материал · линия и способ ответа сверены со спецификацией ФИПИ-2026";

function clean(value) {
  const rounded = Math.round((value + Number.EPSILON) * 1000000) / 1000000;
  return String(rounded);
}

function base(variant, line, topic, prompt, solution, extra = {}) {
  return {
    id: `physics-v${variant}-${line}`,
    subject: SUBJECT,
    number: `Задание ${line}`,
    examYear: 2026,
    sourceLabel: SOURCE,
    difficulty: line >= 21 ? "высокий" : line >= 14 ? "повышенный" : "базовый",
    topic,
    theory: extra.theory ?? "Выпишите известные величины, выберите физический закон и проверьте размерность результата.",
    prompt,
    answer: extra.answer ?? "teacher-review",
    responseInstruction: extra.responseInstruction,
    solution,
    ...extra,
  };
}

function short(variant, line, topic, prompt, answer, solution, extra = {}) {
  return base(variant, line, topic, prompt, solution, {
    kind: "number",
    format: "краткий числовой ответ",
    interaction: "exam-blank",
    answer: String(answer),
    responseInstruction: "Запишите только число без единиц измерения.",
    ...extra,
  });
}

function digits(variant, line, topic, prompt, options, answer, solution, extra = {}) {
  return base(variant, line, topic, prompt, solution, {
    kind: "text",
    format: extra.format ?? "последовательность цифр",
    interaction: "exam-blank",
    answerOrder: extra.answerOrder ?? "fixed",
    options,
    answer: String(answer),
    responseInstruction: extra.responseInstruction ?? "Запишите последовательность цифр без пробелов и других символов.",
    ...extra,
  });
}

function extended(variant, line, topic, prompt, solution, maxScore, extra = {}) {
  return base(variant, line, topic, prompt, solution, {
    kind: "extended",
    format: "развёрнутое решение",
    answer: "teacher-review",
    responseInstruction: "Запишите физические законы, преобразования, вычисления и итог с единицами измерения.",
    maxScore,
    ...extra,
  });
}

