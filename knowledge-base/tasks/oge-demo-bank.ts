function RussianOgeTask(variant: number, number: number, task: Omit<ExamTask, "id" | "subject" | "number">): ExamTask {
  return {
    id: `oge-russian-v${variant}-${number}`,
    subject: "Русский язык",
    number: `Задание ${number}`,
    ...task,
  };
}

