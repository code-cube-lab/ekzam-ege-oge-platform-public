function RussianOgeTask(variant: number, number: number, task: Omit<ExamTask, "id" | "subject" | "number">): ExamTask {
  return {
    id: `oge-russian-v${variant}-${number}`,
    subject: "Русский язык",
    number: `Задание ${number}`,
    examYear: 2026,
    sourceLabel: "Авторский материал · структура ответа сверена со спецификацией ФИПИ-2026",
    difficulty: number === 1 || number === 13 ? "высокий" : number >= 10 ? "повышенный" : "базовый",
    ...task,
  };
}

