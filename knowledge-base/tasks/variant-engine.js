function rotate(items, shift) {
  if (!items?.length) return items;
  const offset = ((shift % items.length) + items.length) % items.length;
  return [...items.slice(offset), ...items.slice(0, offset)];
}

function toExamBlank(task) {
  if (!task?.options?.length || (task.kind !== "single" && task.kind !== "multiple")) return task;
  const answers = Array.isArray(task.answer) ? task.answer : [task.answer];
  const answer = answers
    .map((item) => task.options.findIndex((option) => option === item) + 1)
    .filter((index) => index > 0)
    .sort((a, b) => a - b)
    .join("");
  return {
    ...task,
    kind: "text",
    interaction: "exam-blank",
    answerOrder: answers.length > 1 ? "any" : "fixed",
    answer,
    format: answers.length > 1 ? "последовательность цифр" : "цифра",
    responseInstruction: answers.length > 1
      ? "Запишите номера всех выбранных позиций слитно, без пробелов и запятых."
      : "Запишите номер выбранной позиции.",
  };
}

function authoredExamMeta(task, difficulty = "базовый") {
  return {
    examYear: 2026,
    sourceLabel: "Авторский материал · структура ответа сверена со спецификацией ФИПИ-2026",
    difficulty,
    ...task,
  };
}

function examBlankTask(task, difficulty = "базовый") {
  return authoredExamMeta({
    interaction: "exam-blank",
    answerOrder: task.answerOrder ?? "fixed",
    responseInstruction: task.responseInstruction ?? "Запишите ответ в поле без пробелов и лишних знаков.",
    ...task,
  }, difficulty);
}

function matchingTask({ id, subject, number, topic, theory, prompt, left, right, pairs, shift = 0, solution }) {
  const options = rotate(right, shift);
  const answer = pairs.map((item) => options.findIndex((candidate) => candidate === item) + 1).join("");
  return examBlankTask({
    id,
    subject,
    number,
    kind: "text",
    format: "установление соответствия",
    topic,
    theory,
    stimulus: left.map((item, index) => `${String.fromCharCode(1040 + index)}) ${item}`).join("\n"),
    prompt,
    options,
    answer,
    responseInstruction: "Запишите в порядке А–Д пять цифр, соответствующих выбранным позициям.",
    solution: [solution, `Ответ: ${answer}.`],
  }, "повышенный");
}

