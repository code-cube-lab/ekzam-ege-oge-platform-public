function routeDifficulty(index, fullTaskCount, profile) {
  if (profile?.extendedFrom && index + 1 >= profile.extendedFrom) return "высокий";
  return index + 1 > Math.ceil(fullTaskCount * 0.55) ? "повышенный" : "базовый";
}

function fiveOptionSet(options = [], subject, line) {
  const result = [...options];
  const fallbacks = [
    `Для ${subject.toLowerCase()} вывод не следует из приведённых данных`,
    `Условие задания ${line} не выполняется ни в одном из перечисленных случаев`,
    "Полученный результат противоречит обязательному ограничению условия",
  ];
  for (const fallback of fallbacks) {
    if (result.length >= 5) break;
    if (!result.includes(fallback)) result.push(fallback);
  }
  return result;
}

function genericTask(seed, subjectSlug, index, variant, topics, fullTaskCount) {
  const line = index + 1;
  const profile = subjectExamProfiles[subjectSlug] ?? { extendedFrom: null, sections: ["краткий ответ"], note: `${fullTaskCount} заданий` };
  const topic = topics[index % Math.max(1, topics.length)] ?? seed.topic ?? seed.format;
  const difficulty = routeDifficulty(index, fullTaskCount, profile);
  const common = {
    ...seed,
    id: `${subjectSlug}-v${variant}-${line}`,
    number: `Задание ${line}`,
    topic,
    examYear: 2026,
    sourceLabel: "Черновик предметного банка · не допущен к ученикам",
    difficulty,
    theory: seed.theory ?? `Определите проверяемый элемент темы «${topic}», выпишите данные и проверьте каждый шаг решения. Ошибка в промежуточном действии должна быть найдена до переноса ответа в бланк.`,
  };
  const requiresExtended = Boolean(profile.extendedFrom && line >= profile.extendedFrom);
  if (requiresExtended) {
    return {
      ...common,
      kind: "extended",
      format: subjectSlug === "literature" ? "развёрнутый литературоведческий ответ" : "развёрнутое решение",
      interaction: undefined,
      options: undefined,
      answer: "teacher-review",
      prompt: `${seed.prompt} Запишите полное обоснование для линии ${line}: исходные данные, ход решения и проверяемый вывод. Краткий ответ без объяснения не оценивается как развёрнутое решение.`,
      responseInstruction: "Приведите последовательное решение и итоговый ответ.",
      solution: [
        ...seed.solution,
        "Сверьте каждый переход с условием и объясните, почему выбранный способ применим.",
        "Итоговую оценку развёрнутого решения выполняет преподаватель по предметным критериям.",
      ],
    };
  }
  if (seed.kind === "extended") {
    return {
      ...common,
      kind: "text",
      format: "краткий ответ",
      interaction: "exam-blank",
      answer: String(variant + line),
      answerOrder: "fixed",
      prompt: `По приведённому условию определите номер корректного вывода для темы «${topic}». ${routeContextAngles[(variant + line) % routeContextAngles.length]}`,
      options: undefined,
      responseInstruction: "Запишите полученное число.",
      solution: [`Для этого авторского тренировочного набора контрольный ответ — ${variant + line}.`, ...seed.solution],
    };
  }
  const options = seed.options?.length ? rotate(fiveOptionSet(seed.options, seed.subject, line), variant + index) : undefined;
  const prompt = `Линия ${line}. ${seed.prompt} ${routeContextAngles[(variant + line) % routeContextAngles.length]}`;
  const prepared = {
    ...common,
    prompt,
    options,
  };
  if (options && (seed.kind === "single" || seed.kind === "multiple")) return toExamBlank(prepared);
  return examBlankTask(prepared, difficulty);
}

export function buildTrainingVariant(subjectSlug, fullTaskCount, topics, seeds, variantId = 1) {
  const variant = Math.min(12, Math.max(1, Number(variantId) || 1));
  if (subjectSlug === "russian") return Array.from({ length: fullTaskCount }, (_, index) => russianTask(index, variant));
  if (subjectSlug === "math") return Array.from({ length: fullTaskCount }, (_, index) => mathTask(index, variant));
  const offset = (variant - 1) * 3;
  const automaticSeeds = seeds.filter((task) => task.kind !== "extended");
  const extendedSeeds = seeds.filter((task) => task.kind === "extended");
  const profile = subjectExamProfiles[subjectSlug];
  return Array.from({ length: fullTaskCount }, (_, index) => {
    const line = index + 1;
    const pool = profile?.extendedFrom && line >= profile.extendedFrom && extendedSeeds.length ? extendedSeeds : automaticSeeds.length ? automaticSeeds : seeds;
    return genericTask(pool[(index + offset) % pool.length], subjectSlug, index, variant, topics, fullTaskCount);
  });
}

export function analyzeTaskResults(tasks, results) {
  const topicStats = new Map();
  for (const task of tasks) {
    const state = results[task.id];
    if (!state) continue;
    const topic = task.topic || "общая подготовка";
    const item = topicStats.get(topic) || { correct: 0, incorrect: 0, review: 0 };
    item[state] += 1;
    topicStats.set(topic, item);
  }
  const ranked = [...topicStats.entries()].map(([topic, stats]) => ({ topic, ...stats }));
  return {
    strengths: ranked.filter((item) => item.correct > item.incorrect).sort((a, b) => b.correct - a.correct).map((item) => item.topic),
    weaknesses: ranked.filter((item) => item.incorrect > 0).sort((a, b) => b.incorrect - a.incorrect).map((item) => item.topic),
    reviewTopics: ranked.filter((item) => item.review > 0).map((item) => item.topic),
  };
}
