function familyCommon(family, index) {
  return {
    id: `russian-${family.id}-${index + 1}`,
    subject: "Русский язык",
    number: `Задание ${family.egeNumber}`,
    topic: family.topic,
    familyId: family.id,
    theory: family.theory,
  };
}

function buildFamilyTask(family, index) {
  const common = familyCommon(family, index);
  if (family.id === "stress") {
    const [options, answer, explanation] = stressCases[index];
    return { ...common, kind: "single", format: "один ответ", prompt: "В каком слове верно выделена буква, обозначающая ударный гласный?", options, answer, solution: [explanation] };
  }
  if (family.id === "paronyms") {
    const [prompt, answer, explanation] = paronymCases[index];
    return { ...common, kind: "text", format: "краткий ответ", prompt: `${prompt} Запишите подходящий пароним.`, answer, solution: [explanation] };
  }
  if (family.id === "lexical") {
    const [prompt, answer, explanation] = lexicalCases[index];
    return { ...common, kind: "text", format: "краткий ответ", prompt, answer, solution: [explanation] };
  }
  if (family.id === "morphology") {
    const [phrases, answer, explanation] = morphologyCases[index];
    return { ...common, kind: "text", format: "краткий ответ", prompt: `В одном выделенном слове допущена грамматическая ошибка. Исправьте её и запишите слово правильно:\n${phrases.join(" · ")}`, answer, solution: [explanation] };
  }
  if (family.id === "roots") {
    const [options, answer, explanation] = rootCases[index];
    return { ...common, kind: "single", format: "один ответ", prompt: "В каком слове пропущена проверяемая безударная гласная корня?", options, answer, solution: [`${explanation}.`] };
  }
  if (family.id === "prefixes") {
    const [options, answer, explanation] = prefixCases[index];
    return { ...common, kind: "single", format: "один ответ", prompt: prefixPrompts[index], options, answer, solution: [explanation] };
  }
  if (family.id === "suffixes") {
    const [options, answer, explanation] = suffixCases[index];
    return { ...common, kind: "single", format: "один ответ", prompt: `В каком слове на месте пропуска пишется буква ${suffixLetters[index]}?`, options, answer, solution: [explanation] };
  }
  if (family.id === "endings") {
    const [options, answer, explanation] = endingCases[index];
    return { ...common, kind: "single", format: "один ответ", prompt: `В каком слове на месте пропуска пишется буква ${endingLetters[index]}?`, options, answer, solution: [explanation] };
  }
  if (family.id === "not-ni") {
    const [options, answer, explanation] = notNiCases[index];
    return { ...common, kind: "single", format: "один ответ", prompt: "В каком варианте НЕ со словом пишется слитно?", options, answer, solution: [explanation] };
  }
  if (family.id === "joined") {
    const [options, answer, explanation] = joinedCases[index];
    const prompt = index === 2 ? "В каком варианте выделенное слово пишется через дефис?" : "В каком варианте выделенное слово пишется слитно?";
    return { ...common, kind: "single", format: "один ответ", prompt, options, answer, solution: [explanation] };
  }
  if (family.id === "nn") {
    const [options, answer, explanation] = nnCases[index];
    return { ...common, kind: "multiple", format: "несколько ответов", prompt: "Выберите все слова, в которых на месте пропуска пишется НН.", options, answer, solution: [explanation] };
  }
  if (family.id === "punctuation") {
    if (index < punctuationCases.length) {
      const [prompt, options, answer, explanation] = punctuationCases[index];
      return { ...common, kind: "single", format: "один ответ", prompt, options, answer, solution: [explanation] };
    }
    const [options, answer] = commaCases[index - punctuationCases.length];
    return { ...common, kind: "multiple", format: "несколько ответов", prompt: "Выберите предложения, в которых нужно поставить запятую.", options, answer, solution: ["Сначала найдите грамматические основы и границы частей; затем определите правило для каждого знака."] };
  }
  if (family.id === "expression") {
    const [quote, options, answer] = expressionCases[index];
    return { ...common, kind: "single", format: "один ответ", prompt: `Какое средство выразительности использовано: ${quote}?`, options, answer, solution: [`Верный термин: ${answer}.`] };
  }
  const [theme, instruction] = essayCases[index];
  return {
    ...common,
    kind: "extended",
    format: "развёрнутый ответ",
    prompt: `Напишите фрагмент сочинения по проблеме ${theme}. ${instruction} Не менее 80 знаков.`,
    answer: "teacher-review",
    solution: ["Назовите позицию автора своими словами.", "Приведите два точных примера и объясните смысловую связь.", "Сформулируйте и обоснуйте собственное отношение; итоговую проверку выполняет преподаватель."],
  };
}

export function getRussianTaskFamily(familyId = "stress") {
  return russianTaskFamilies.find((family) => family.id === familyId) ?? russianTaskFamilies[0];
}

export function getRussianFamilyTasks(familyId = "stress", limit) {
  const family = getRussianTaskFamily(familyId);
  const count = Math.min(family.count, Number(limit) > 0 ? Number(limit) : family.count);
  return Array.from({ length: count }, (_, index) => toExamBlank(buildFamilyTask(family, index)));
}

export function getRussianAuthorBankSize() {
  return russianTaskFamilies.reduce((sum, family) => sum + family.count, 0);
}

function cleanNumber(value) {
  return String(Number(value.toFixed(6)));
}

